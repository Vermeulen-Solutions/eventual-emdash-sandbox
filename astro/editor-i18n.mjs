export function editorText(value, locale = "en") {
  if (!String(locale).toLowerCase().startsWith("fr") || typeof value !== "string") return value;
  if (french[value]) return french[value];
  for(const reason of ["Publish a valid referenced venue before publishing or scheduling this event.","Publish the referenced organizer before publishing or scheduling this event."]) if(value.includes(reason)) return french[reason];
  const count = /^(\d+) dates in this window\. Schedule changes affect every language; announcement changes affect (.+) only\.$/.exec(value);
  if (count) return `${count[1]} date${count[1] === "1" ? "" : "s"} dans cette période. Les dates sont communes à toutes les langues ; l’annonce concerne uniquement ${count[2]}.`;
  if (value.startsWith("Manage ")) return "Gérer " + value.slice(7);
  if (value.endsWith(" (all day)")) return value.slice(0, -10) + " (journée entière)";
  if (value.endsWith(" (publish before the event)")) return value.replace(" (publish before the event)", " (à publier avant l’événement)");
  const recurrence = /^(.*?) through (\d{4}-\d{2}-\d{2})$/.exec(value);
  if (recurrence) {
    const [frequency, detail] = recurrence[1].split(" on ");
    const interval = /^every (\d+) (days|weeks|months)$/.exec(frequency);
    let summary = { daily: "Chaque jour", weekly: "Chaque semaine", monthly: "Chaque mois", "every week": "Chaque semaine" }[frequency] ?? frequency;
    if (interval) summary = (interval[2] === "weeks" ? "Toutes les " : "Tous les ") + interval[1] + " " + { days: "jours", weeks: "semaines", months: "mois" }[interval[2]];
    if (detail) {
      const day = /^day (\d+) \((skip missing months|use last day if missing)\)$/.exec(detail);
      if (day) summary += `, le ${day[1]} (${day[2] === "skip missing months" ? "mois sans cette date ignorés" : "dernier jour du mois si cette date n’existe pas"})`;
      else summary += ", le " + detail.split(", ").map(part => part.split(" ").map(word => french[word[0].toUpperCase() + word.slice(1)]?.toLowerCase() ?? word).join(" ")).join(" et le ");
    }
    return summary + " jusqu’au " + new Intl.DateTimeFormat(locale, { dateStyle: "long", timeZone: "UTC" }).format(new Date(recurrence[2] + "T00:00:00Z"));
  }
  return value;
}
